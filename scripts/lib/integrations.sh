#!/usr/bin/env bash

# Optional integrations and session-specific post install steps.

apply_flatpak_theme_override() {
  local theme_name="$1"

  if ! has_command flatpak; then
    return
  fi

  echo -e "\nApplying Flatpak theme override (GTK_THEME=${theme_name})..."

  flatpak override --user --env=GTK_THEME="${theme_name}" 2> /dev/null || true
  flatpak override --user --filesystem=xdg-config/gtk-3.0:ro 2> /dev/null || true
  flatpak override --user --filesystem=xdg-config/gtk-4.0:ro 2> /dev/null || true
  flatpak override --user --filesystem=xdg-data/themes:ro 2> /dev/null || true
  flatpak override --user --filesystem="${HOME}/.themes:ro" 2> /dev/null || true
}

apply_snap_theme_preset() {
  local theme_name="$1"
  local envd_dir="${HOME}/.config/environment.d"
  local preset_file="${envd_dir}/99-cleanframe-theme.conf"

  mkdir -p "${envd_dir}"
  rm -f "${envd_dir}/90-cleanframe-theme.conf" 2> /dev/null || true

  local conflict_files=""
  conflict_files="$(grep -RIl '^[[:space:]]*GTK_THEME=' "${envd_dir}" 2> /dev/null | grep -vFx "${preset_file}" || true)"
  if [[ -n "${conflict_files}" ]]; then
    echo "WARNING: conflicting GTK_THEME preset(s) detected in '${envd_dir}':"
    echo "${conflict_files}" | sed 's/^/  - /'
    echo "         '${preset_file##*/}' will override on next login/session reload."
  fi

  cat > "${preset_file}" << EOF
# Generated by CleanFrame install.sh
GTK_THEME=${theme_name}
EOF

  echo -e "\nSnap preset written to '${preset_file}'."
  echo "Log out and log back in to propagate GTK_THEME to desktop-launched snaps."
}

apply_sandbox_theme_preset() {
  local theme_name="$1"

  if [[ "${apply_flatpak_preset:-false}" == "true" ]]; then
    apply_flatpak_theme_override "${theme_name}"
  fi

  if [[ "${apply_snap_preset:-false}" == "true" ]]; then
    apply_snap_theme_preset "${theme_name}"
  fi
}

install_gnome_terminal_profile_from_project() {
  local set_default="${1:-true}"
  local apply_inplace="${2:-false}"
  local installer_script="$REPO_DIR/scripts/install-gnome-terminal-cleanframe.sh"
  local args=()

  # Configure XFCE Terminal if installed and running
  if has_command xfconf-query; then
    if xfconf-query -c xfce4-terminal -p /color-use-theme >/dev/null 2>&1; then
      xfconf-query -c xfce4-terminal -p /color-use-theme -s false 2>/dev/null || true
      xfconf-query -c xfce4-terminal -p /color-background -s '#ffffffffffff' 2>/dev/null || true
      xfconf-query -c xfce4-terminal -p /color-foreground -s '#000000000000' 2>/dev/null || true
    fi
  fi

  if ! has_command gsettings; then
    return 0
  fi

  if ! gsettings list-schemas 2>/dev/null | grep -q "^org\.gnome\.Terminal\.ProfilesList$"; then
    return 0
  fi

  if [[ "$set_default" == "true" ]]; then
    args+=(--set-default)
  fi

  if [[ "$apply_inplace" == "true" ]]; then
    args+=(--apply-to-default-profile)
  fi

  if [[ ! -x "$installer_script" ]]; then
    echo "WARNING: GNOME Terminal installer script not found or not executable."
    echo "         Expected: $installer_script"
    return 1
  fi

  if [[ "$apply_inplace" == "true" ]]; then
    echo -e "\nApplying GNOME Terminal colors to existing default profile (in-place)..."
  else
    echo -e "\nConfiguring GNOME Terminal light profile 'CleanFrame Light'..."
  fi

  if [[ "$UID" -eq "$ROOT_UID" && -n "${SUDO_USER:-}" ]]; then
    local target_uid runtime_dir
    target_uid="$(id -u "$SUDO_USER" 2> /dev/null || true)"
    runtime_dir="/run/user/${target_uid}"

    if [[ -n "$target_uid" && -S "${runtime_dir}/bus" ]]; then
      sudo -u "$SUDO_USER" env \
        XDG_RUNTIME_DIR="$runtime_dir" \
        DBUS_SESSION_BUS_ADDRESS="unix:path=${runtime_dir}/bus" \
        bash "$installer_script" "${args[@]}"
    else
      echo "WARNING: Could not access DBus user session for '$SUDO_USER'."
      echo "         Run manually (without sudo) after install:"
      echo "         bash \"$installer_script\" ${args[*]}"
      return 1
    fi
  else
    bash "$installer_script" "${args[@]}"
  fi
}
